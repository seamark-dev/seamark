// TestSummaryAccountsForEverySeenFile proves the identity that status and
// orient rely on: a seen file that is not parsed, skipped, or a parse
// error has no language extractor. The stored summary has no count of
// those files, so the derived count must match the listed files that the
// registry has no extractor for.
func TestSummaryAccountsForEverySeenFile(t *testing.T) {
	root := t.TempDir()
	writeFixture(t, root)

	extra := map[string]string{
		"gen.go":               "// Code generated by protoc. DO NOT EDIT.\n\npackage main\n\nfunc Generated() {}\n",
		"docs/notes.yaml":      "a: 1\n",
		"scripts/build.sh":     "#!/bin/sh\n",
		".seamark/config.yaml": "index:\n  exclude:\n    - '**/util.go'\n",
	}

	for rel, content := range extra {
		p := filepath.Join(root, filepath.FromSlash(rel))
		require.NoError(t, os.MkdirAll(filepath.Dir(p), 0o755))
		require.NoError(t, os.WriteFile(p, []byte(content), 0o644))
	}

	// A link to a missing target is listed and fails to read.
	require.NoError(t, os.Symlink(filepath.Join(root, "missing.go"), filepath.Join(root, "dangling.go")))

	sum, st := runIndex(t, root)
	require.Equal(t, 2, sum.FilesSkipped, "the generated file and the excluded file")
	require.Equal(t, 1, sum.ParseErrors, "the dangling link")
	require.Positive(t, sum.FilesParsed)

	files, _, _, err := listFiles(root)
	require.NoError(t, err)

	registry, err := parse.NewRegistry()
	require.NoError(t, err)
	defer registry.Close()

	var noExtractor []string

	for _, rel := range files {
		if registry.ForPath(rel) == nil {
			noExtractor = append(noExtractor, rel)
		}
	}

	require.Contains(t, noExtractor, "README.md")
	require.Contains(t, noExtractor, "docs/notes.yaml")

	raw, err := st.GetMeta(store.MetaIndexSummary)
	require.NoError(t, err)

	c := indexhealth.ParseCoverage(raw)
	require.True(t, c.Known, raw)
	assert.Equal(t, len(files), c.FilesSeen)
	assert.Equal(t, len(noExtractor), c.FilesUnsupported, "%v", noExtractor)
}
